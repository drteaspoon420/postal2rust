//! Navigation network baked into POSTAL 2 maps.
//!
//! The editor's "build paths" step stores the AI network in the map:
//! - every `NavigationPoint` actor (PathNode, PlayerStart, Door, AutoLadder, JumpPad, Teleporter,
//!   and POSTAL 2 points such as HomeNode, PatrolNode, ...) is linked into a list that starts at
//!   `LevelInfo.NavigationPointList` and continues through each point's `nextNavigationPoint`;
//! - each point's `PathList` is an array of `ReachSpec` objects, one per outgoing edge, holding
//!   `Start`, `End`, `Distance`, `CollisionRadius`, `CollisionHeight`, `reachFlags`,
//!   `MaxLandingVelocity`, `bPruned` and `bForced`.
//!
//! [`NavGraph::from_package`] reads both from the saved tagged properties (no class defaults
//! needed) and cross-checks them: every chained point, every point owning a PathList, and every
//! ReachSpec endpoint becomes a node. [`VmNav`] maps nodes to the VM objects of an instantiated
//! level and implements [`uscript::nav::NavGraphView`], which the VM's route-finding natives use.
//!
//! Observed in the shipped maps: many points are not on the `NavigationPointList` chain even
//! though they carry PathLists and are referenced by ReachSpecs (e.g. ngt-Church chains 34 of
//! 400). Their own `nextNavigationPoint` links form stale sub-chains from an earlier path build.
//! The engine only walks the chain for whole-network iteration; route search follows PathLists,
//! so every node is kept and [`NavNode::in_chain`] records which ones the chain reaches.
//! `AutoDoor` and most `AutoLadder` points (generated by the path builder) have no PathList.

use std::collections::HashMap;
use upkg::{ObjRef, Package, Reader, Value, begin_object};
use uscript::nav::{NavEdge, NavGraphView};
use uscript::vm::ObjId;

/// `reachFlags` bits (named after the movement each edge needs; values established from the
/// shipped maps, see the README).
pub mod reach {
    pub const WALK: i32 = 1;
    pub const FLY: i32 = 2;
    pub const SWIM: i32 = 4;
    pub const JUMP: i32 = 8;
    pub const DOOR: i32 = 16;
    pub const SPECIAL: i32 = 32;
    pub const LADDER: i32 = 64;
    pub const PROSCRIBED: i32 = 128;
    pub const FORCED: i32 = 256;
    pub const PLAYERONLY: i32 = 512;
}

#[derive(Debug, Clone)]
pub struct NavNode {
    /// Export index in the map package.
    pub export: usize,
    pub name: String,
    pub class: String,
    pub location: [f32; 3],
    pub rotation: [i32; 3],
    /// Collision cylinder saved in the map (0 when the class default applies).
    pub collision_radius: f32,
    pub collision_height: f32,
    pub tag: String,
    /// Outgoing edges (indices into [`NavGraph::specs`]) in PathList order.
    pub paths: Vec<u32>,
    /// Next point in the `nextNavigationPoint` chain.
    pub next: Option<u32>,
    pub in_chain: bool,
    pub extra_cost: i32,
    pub blocked: bool,
    pub one_way: bool,
    pub proscribed: Vec<String>,
    pub forced: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct ReachSpec {
    pub export: usize,
    pub start: u32,
    pub end: u32,
    pub distance: i32,
    pub collision_radius: i32,
    pub collision_height: i32,
    pub reach_flags: i32,
    pub max_landing_velocity: i32,
    pub pruned: bool,
    pub forced: bool,
}

#[derive(Debug, Default)]
pub struct NavGraph {
    pub nodes: Vec<NavNode>,
    pub specs: Vec<ReachSpec>,
    pub by_export: HashMap<usize, u32>,
    /// First point of the chain (`LevelInfo.NavigationPointList`).
    pub head: Option<u32>,
    pub stats: NavStats,
}

#[derive(Debug, Default, Clone)]
pub struct NavStats {
    pub chained: usize,
    pub reach_specs: usize,
    /// ReachSpecs not listed in their Start point's PathList.
    pub orphan_specs: usize,
    /// PathList entries whose ReachSpec starts elsewhere.
    pub mismatched_paths: usize,
    /// Points owning a PathList but missing from the chain.
    pub unchained_points: usize,
    pub property_failures: usize,
    pub bad_refs: usize,
}

fn export_of(r: ObjRef) -> Option<usize> {
    match r {
        ObjRef::Export(i) => Some(i),
        _ => None,
    }
}

/// Object references stored in a dynamic array property (compact count + compact refs).
fn ref_array(raw: &[u8]) -> Option<Vec<ObjRef>> {
    let mut r = Reader::new(raw);
    let n = r.count().ok()?;
    let mut v = Vec::with_capacity(n);
    for _ in 0..n {
        v.push(ObjRef::from_raw(r.compact().ok()?));
    }
    (r.pos() == raw.len()).then_some(v)
}

impl NavGraph {
    pub fn from_package(pkg: &Package) -> NavGraph {
        let mut g = NavGraph::default();
        let mut raw_specs: Vec<(usize, upkg::Properties)> = Vec::new();
        let mut point_props: HashMap<usize, upkg::Properties> = HashMap::new();
        let mut head = None;
        for i in 0..pkg.exports.len() {
            let class = pkg.export_class(i);
            let want = class == "ReachSpec" || class == "LevelInfo";
            // Navigation points are recognised by their saved nav properties below; reading every
            // actor's properties is cheap enough at map load.
            if !want && pkg.exports[i].size == 0 {
                continue;
            }
            let Ok((_, props)) = begin_object(pkg, i) else {
                if want {
                    g.stats.property_failures += 1;
                }
                continue;
            };
            match class {
                "ReachSpec" => raw_specs.push((i, props)),
                "LevelInfo" => head = props.object("NavigationPointList").and_then(export_of),
                _ => {
                    if props.get("PathList").is_some() || props.get("nextNavigationPoint").is_some() {
                        point_props.insert(i, props);
                    }
                }
            }
        }
        // Chain order first, so node indices follow the engine's list.
        let mut chain = Vec::new();
        let mut cur = head;
        while let Some(e) = cur {
            if chain.len() > pkg.exports.len() || chain.contains(&e) {
                break;
            }
            chain.push(e);
            if !point_props.contains_key(&e) {
                if let Ok((_, p)) = begin_object(pkg, e) {
                    point_props.insert(e, p);
                }
            }
            cur = point_props.get(&e).and_then(|p| p.object("nextNavigationPoint")).and_then(export_of);
        }
        g.stats.chained = chain.len();
        let mut order = chain.clone();
        let mut rest: Vec<usize> = point_props.keys().copied().filter(|e| !chain.contains(e)).collect();
        rest.sort();
        g.stats.unchained_points = rest.iter().filter(|e| point_props[e].get("PathList").is_some()).count();
        order.extend(rest);
        for &(_, ref p) in &raw_specs {
            for k in ["Start", "End"] {
                if let Some(e) = p.object(k).and_then(export_of) {
                    if !order.contains(&e) {
                        order.push(e);
                    }
                }
            }
        }
        for (k, &e) in order.iter().enumerate() {
            g.by_export.insert(e, k as u32);
        }
        for &e in &order {
            let p = match point_props.get(&e) {
                Some(p) => p.clone(),
                None => begin_object(pkg, e).map(|x| x.1).unwrap_or_default(),
            };
            let names = |key: &str| (0..4).filter_map(|i| match p.get_at(key, i) {
                Some(Value::Name(n)) if !n.eq_ignore_ascii_case("None") => Some(n.clone()),
                _ => None,
            }).collect::<Vec<_>>();
            g.nodes.push(NavNode {
                export: e,
                name: pkg.name(pkg.exports[e].name).to_string(),
                class: pkg.export_class(e).to_string(),
                location: p.vector("Location").unwrap_or_default(),
                rotation: p.rotator("Rotation").unwrap_or_default(),
                collision_radius: p.float("CollisionRadius").unwrap_or(0.0),
                collision_height: p.float("CollisionHeight").unwrap_or(0.0),
                tag: match p.get("Tag") {
                    Some(Value::Name(n)) => n.clone(),
                    _ => String::new(),
                },
                paths: Vec::new(),
                next: p.object("nextNavigationPoint").and_then(export_of).and_then(|n| g.by_export.get(&n).copied()),
                in_chain: chain.contains(&e),
                extra_cost: p.int("ExtraCost").unwrap_or(0),
                blocked: p.bool("bBlocked").unwrap_or(false),
                one_way: p.bool("bOneWayPath").unwrap_or(false),
                proscribed: names("ProscribedPaths"),
                forced: names("ForcedPaths"),
            });
        }
        g.head = head.and_then(|h| g.by_export.get(&h).copied());
        // ReachSpecs.
        let mut spec_by_export = HashMap::new();
        for (e, p) in &raw_specs {
            let node = |k: &str| p.object(k).and_then(export_of).and_then(|x| g.by_export.get(&x).copied());
            let (Some(start), Some(end)) = (node("Start"), node("End")) else {
                g.stats.bad_refs += 1;
                continue;
            };
            spec_by_export.insert(*e, g.specs.len() as u32);
            g.specs.push(ReachSpec {
                export: *e,
                start,
                end,
                distance: p.int("Distance").unwrap_or(0),
                collision_radius: p.int("CollisionRadius").unwrap_or(0),
                collision_height: p.int("CollisionHeight").unwrap_or(0),
                reach_flags: p.int("reachFlags").unwrap_or(0),
                max_landing_velocity: p.int("MaxLandingVelocity").unwrap_or(0),
                pruned: matches!(p.get("bPruned"), Some(Value::Byte(b)) if *b != 0),
                forced: p.bool("bForced").unwrap_or(false),
            });
        }
        g.stats.reach_specs = g.specs.len();
        // PathLists.
        let mut listed = vec![false; g.specs.len()];
        for k in 0..g.nodes.len() {
            let e = g.nodes[k].export;
            let Some(Value::Array { raw }) = point_props.get(&e).and_then(|p| p.get("PathList")) else { continue };
            let Some(refs) = ref_array(raw) else {
                g.stats.property_failures += 1;
                continue;
            };
            for r in refs {
                match export_of(r).and_then(|x| spec_by_export.get(&x)) {
                    Some(&s) if g.specs[s as usize].start == k as u32 => {
                        listed[s as usize] = true;
                        g.nodes[k].paths.push(s);
                    }
                    Some(_) => g.stats.mismatched_paths += 1,
                    None => g.stats.bad_refs += 1,
                }
            }
        }
        g.stats.orphan_specs = listed.iter().filter(|l| !**l).count();
        g
    }

    pub fn node_by_name(&self, name: &str) -> Option<u32> {
        self.nodes.iter().position(|n| n.name.eq_ignore_ascii_case(name)).map(|i| i as u32)
    }

    /// Node count per class name.
    pub fn class_counts(&self) -> std::collections::BTreeMap<String, usize> {
        let mut m = std::collections::BTreeMap::new();
        for n in &self.nodes {
            *m.entry(n.class.clone()).or_default() += 1;
        }
        m
    }
}

/// A decoded graph bound to the VM objects of an instantiated level.
pub struct VmNav {
    pub graph: NavGraph,
    node_obj: Vec<Option<ObjId>>,
    spec_obj: Vec<Option<ObjId>>,
    obj_node: HashMap<ObjId, u32>,
    edges: Vec<Vec<NavEdge>>,
}

impl VmNav {
    /// `objects` maps map-package export indices to the VM objects created for them
    /// (`p2game::level::Level::objects`).
    pub fn new(graph: NavGraph, objects: &HashMap<usize, ObjId>) -> VmNav {
        let node_obj: Vec<Option<ObjId>> = graph.nodes.iter().map(|n| objects.get(&n.export).copied()).collect();
        let spec_obj = graph.specs.iter().map(|s| objects.get(&s.export).copied()).collect();
        let obj_node = node_obj.iter().enumerate().filter_map(|(k, o)| o.map(|o| (o, k as u32))).collect();
        let edges = graph
            .nodes
            .iter()
            .map(|n| {
                n.paths
                    .iter()
                    .map(|&s| {
                        let sp = &graph.specs[s as usize];
                        NavEdge {
                            end: sp.end,
                            spec: s,
                            distance: sp.distance,
                            collision_radius: sp.collision_radius,
                            collision_height: sp.collision_height,
                            reach_flags: sp.reach_flags,
                            max_landing_velocity: sp.max_landing_velocity,
                        }
                    })
                    .collect()
            })
            .collect();
        VmNav { graph, node_obj, spec_obj, obj_node, edges }
    }
}

impl NavGraphView for VmNav {
    fn node_count(&self) -> usize {
        self.graph.nodes.len()
    }
    fn node_obj(&self, n: u32) -> Option<ObjId> {
        self.node_obj.get(n as usize).copied().flatten()
    }
    fn obj_node(&self, o: ObjId) -> Option<u32> {
        self.obj_node.get(&o).copied()
    }
    fn node_location(&self, n: u32) -> [f32; 3] {
        self.graph.nodes[n as usize].location
    }
    fn edges(&self, n: u32) -> &[NavEdge] {
        &self.edges[n as usize]
    }
    fn spec_obj(&self, spec: u32) -> Option<ObjId> {
        self.spec_obj.get(spec as usize).copied().flatten()
    }
}
